/**
 * Plain text from a pages.json HTML/text field (tokens replaced, tags and shortcodes removed).
 */
function am_plain( string $html ): string {
	$text = am_tokens( $html );
	$text = preg_replace( '/\[\/?am_[^\]]*\]/', '', $text );
	$text = wp_strip_all_tags( $text );
	return trim( preg_replace( '/\s+/', ' ', html_entity_decode( $text, ENT_QUOTES | ENT_HTML5, 'UTF-8' ) ) );
}

/**
 * Pages grouped for llms.txt: section label => list of pages.json entries.
 */
function am_llms_groups(): array {
	$groups = array(
		'Aggregate calculators' => array(),
		'Merit lists'           => array(),
		'Tools and open data'   => array(),
		'Guides'                => array(),
		'Data reports'          => array(),
		'About and policies'    => array(),
	);
	foreach ( (array) ( am_data( 'pages' )['pages'] ?? array() ) as $p ) {
		$path = (string) ( $p['path'] ?? '' );
		if ( '' === $path || '/' === $path || ! empty( $p['noindex'] ) ) {
			continue;
		}
		$tpl = (string) ( $p['template'] ?? 'default' );
		if ( 'trust' === ( $p['type'] ?? '' ) && ! in_array( $path, array( '/data/', '/submit-merit-list/' ), true ) ) {
			$key = 'About and policies';
		} elseif ( str_starts_with( $path, '/guides/' ) ) {
			$key = 'Guides';
		} elseif ( str_starts_with( $path, '/merit-data-report-' ) ) {
			$key = 'Data reports';
		} elseif ( 'calculator' === $tpl && '/predictor/' !== $path ) {
			$key = 'Aggregate calculators';
		} elseif ( 'meritlist' === $tpl && '/merit-list/' !== $path ) {
			$key = 'Merit lists';
		} else {
			$key = 'Tools and open data';
		}
		$groups[ $key ][] = $p;
	}
	return array_filter( $groups );
}

/**
 * Absolute URL on the canonical domain (site.json url). The llms files are written on the first
 * request after a deploy, which can arrive on Hostinger's temporary domain, so home_url() is not safe here.
 */
function am_llms_url( string $path ): string {
	return untrailingslashit( am_site_url() ) . '/' . ltrim( $path, '/' );
}

/**
 * Header shared by llms.txt and llms-full.txt.
 */
function am_llms_head(): string {
	$home  = am_find_page( '/' );
	$brand = (string) am_site( 'brand', 'Apna Merit' );
	$out   = '# ' . $brand . "\n\n";
	$out  .= '> ' . am_plain( (string) ( $home['description'] ?? am_site( 'tagline' ) ) ) . "\n\n";
	$out  .= $brand . ' (' . am_site_url() . ') publishes aggregate calculators, program-wise closing merits and an admission chance predictor for Pakistani universities. ';
	$out  .= 'Every formula and closing aggregate is copied from an official university, UHS or PMDC document and links to it. ';
	$out  .= $brand . ' is independent and not affiliated with any university.' . "\n\n";
	$out  .= '- Admission season: ' . am_site( 'season_year' ) . '; newest merit data year: ' . am_site( 'data_year' ) . " (each university shows its own newest official year).\n";
	$out  .= '- Closing aggregate = aggregate of the last candidate admitted in that merit list; percentages have 2 decimals unless the source prints more.' . "\n";
	$out  .= '- Data licence: ' . am_site( 'data_license.name' ) . ' (' . am_site( 'data_license.url' ) . '); ' . am_site( 'data_license.attribution' ) . ".\n";
	$out  .= '- Machine-readable data: ' . am_llms_url( '/data/index.json' ) . ' (one JSON file per university).' . "\n";
	$out  .= '- Editor: ' . am_site( 'author.name' ) . ' (' . am_llms_url( '/about/' ) . '). Corrections: ' . am_site( 'contact.email' ) . ".\n";
	$out  .= '- Last generated: ' . gmdate( 'Y-m-d' ) . ".\n\n";
	return $out;
}

/**
 * /llms.txt (llmstxt.org format): H1, summary, then H2 sections of "- [name](url): description".
 */
function am_llms_txt(): string {
	$out = am_llms_head();
	foreach ( am_llms_groups() as $label => $pages ) {
		$out .= '## ' . $label . "\n\n";
		foreach ( $pages as $p ) {
			$out .= '- [' . am_plain( (string) ( $p['h1'] ?? $p['title'] ?? '' ) ) . '](' . am_llms_url( (string) $p['path'] ) . '): ' . am_plain( (string) ( $p['description'] ?? '' ) ) . "\n";
		}
		$out .= "\n";
	}
	$out .= "## Optional\n\n";
	$out .= '- [Full text for LLMs](' . am_llms_url( '/llms-full.txt' ) . '): every answer, formula, FAQ and default merit table on one page, in Markdown.' . "\n";
	$out .= '- [Open data index](' . am_llms_url( '/data/index.json' ) . '): JSON list of every university dataset.' . "\n\n";
	return $out . AM_LLMS_SIGNATURE . "\n";
}

/**
 * Markdown table of a university's default view (year, list, category).
 */
function am_merit_markdown( array $uni ): string {
	$rows = am_default_rows( $uni );
	if ( ! $rows ) {
		return '';
	}
	$year  = am_uni_year( $uni, $list, $cat );
	$cur   = array_values( array_filter( $rows, fn( $r ) => (int) $r['year'] === $year ) );
	usort( $cur, fn( $a, $b ) => (float) $b['closing'] <=> (float) $a['closing'] );
	$cell = fn( $s ) => str_replace( array( '|', "\n" ), array( '/', ' ' ), (string) $s );
	$out  = '| Program | Campus | Shift | Closing aggregate | Source |' . "\n" . '|---|---|---|---|---|' . "\n";
	foreach ( $cur as $r ) {
		$out .= '| ' . $cell( $r['program'] ) . ' | ' . $cell( $r['campus'] ?? '' ) . ' | ' . $cell( $r['shift'] ?? '' ) . ' | ' . am_pct( $r['closing'] ) . ' | ' . $cell( $r['source_url'] ) . " |\n";
	}
	return '**' . ( $uni['short'] ?? '' ) . ', ' . $year . ', ' . ( $uni['defaults']['list'] ?? 'Final' ) . ' list, ' . strtolower( (string) ( $uni['defaults']['category'] ?? 'Open merit' ) ) . "**\n\n" . $out . "\n";
}

/**
 * /llms-full.txt: llms.txt header + every page's answer and FAQ, every formula, every default merit table.
 */
function am_llms_full_txt(): string {
	$out  = am_llms_head();
	$unis = am_unis();
	$by   = array();
	foreach ( $unis as $uni ) {
		foreach ( array( 'calculator_path', 'meritlist_path' ) as $k ) {
			if ( ! empty( $uni[ $k ] ) ) {
				$by[ (string) $uni[ $k ] ][] = array( $k, $uni );
			}
		}
	}
	foreach ( am_llms_groups() as $label => $pages ) {
		if ( 'About and policies' === $label ) {
			continue;
		}
		$out .= '## ' . $label . "\n\n";
		foreach ( $pages as $p ) {
			$path = (string) $p['path'];
			$out .= '### ' . am_plain( (string) ( $p['h1'] ?? $p['title'] ?? '' ) ) . "\n\n" . 'URL: ' . am_llms_url( $path ) . "\n\n";
			$answer = am_plain( (string) ( $p['answer'] ?? '' ) );
			$out   .= ( '' !== $answer ? $answer : am_plain( (string) ( $p['description'] ?? '' ) ) ) . "\n\n";
			foreach ( $by[ $path ] ?? array() as list( $kind, $uni ) ) {
				if ( 'calculator_path' === $kind ) {
					foreach ( (array) ( $uni['formulas'] ?? array() ) as $f ) {
						$out .= '- Formula (' . am_plain( (string) ( $f['label'] ?? '' ) ) . '): ' . am_formula_summary( $f ) . '. Source: ' . ( $f['source_url'] ?? '' ) . "\n";
					}
					$out .= "\n";
				} else {
					foreach ( am_quotables( $uni ) as $q ) {
						$out .= '- ' . $q . "\n";
					}
					$out .= "\n" . am_merit_markdown( $uni );
				}
			}
			$faq = array_filter( (array) ( $p['faq'] ?? array() ), fn( $f ) => empty( $f['lang'] ) || str_starts_with( (string) $f['lang'], 'en' ) );
			if ( $faq ) {
				$out .= "FAQ:\n\n";
				foreach ( $faq as $f ) {
					$out .= '- Q: ' . am_plain( (string) ( $f['q'] ?? '' ) ) . "\n  A: " . am_plain( (string) ( $f['a'] ?? '' ) ) . "\n";
				}
				$out .= "\n";
			}
		}
	}
	$out .= "## About and policies\n\n";
	foreach ( am_llms_groups()['About and policies'] ?? array() as $p ) {
		$out .= '- [' . am_plain( (string) ( $p['h1'] ?? $p['title'] ?? '' ) ) . '](' . am_llms_url( (string) $p['path'] ) . '): ' . am_plain( (string) ( $p['description'] ?? '' ) ) . "\n";
	}
	return $out . "\n" . AM_LLMS_SIGNATURE . "\n";
}

/**
 * Write llms.txt and llms-full.txt into the WordPress root, replacing only a missing file,
 * Hostinger's generated one or our own. Returns the files written.
 */
function am_llms_write(): array {
	$done = array();
	foreach ( array( 'llms.txt' => 'am_llms_txt', 'llms-full.txt' => 'am_llms_full_txt' ) as $name => $fn ) {
		$file = ABSPATH . $name;
		if ( file_exists( $file ) ) {
			$old = (string) @file_get_contents( $file );
			if ( ! str_contains( $old, AM_LLMS_HOSTINGER_SIGNATURE ) && ! str_contains( $old, AM_LLMS_SIGNATURE ) ) {
				continue; // Someone wrote it by hand: leave it.
			}
		}
		if ( false !== @file_put_contents( $file, $fn(), LOCK_EX ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions
			$done[] = $name;
		}
	}
	return $done;
}

// Rebuild after every deploy (inc/deploy.php fires am_deployed once per new fingerprint).
add_action( 'am_deployed', 'am_llms_write' );

// Fallback route when the files could not be written (no static file → WordPress handles the URL).
add_action(
	'template_redirect',
	function () {
		$path = am_request_path();
		if ( '/llms.txt' !== $path && '/llms-full.txt' !== $path ) {
			return;
		}
		status_header( 200 );
		header( 'Content-Type: text/plain; charset=utf-8' );
		header( 'X-Robots-Tag: noindex' );
		header( 'Cache-Control: public, max-age=3600' );
		echo '/llms.txt' === $path ? am_llms_txt() : am_llms_full_txt(); // phpcs:ignore WordPress.Security.EscapeOutput -- plain text
		exit;
	},
	-2
);
