<?php
/**
 * Phase 6 answer-engine (AEO/GEO) features.
 *
 *   am_quotables()     self-contained "quotable" sentences generated from merit data
 *   am_facts_html()    "Key figures" list under every merit table
 *   /llms.txt          site map for LLMs (pages grouped, one line each, licence, contact)
 *   /llms-full.txt     the same plus every answer block, formula, FAQ and default merit table as Markdown
 *
 * Hostinger serves a static /llms.txt from public_html when its Tools plugin generated one, so the
 * theme writes both files into ABSPATH after each deploy (am_llms_write). The plugin never touches a
 * file without its signature line. If the folder is not writable, the route below serves them.
 */

defined( 'ABSPATH' ) || exit;

/** Signature the Hostinger Tools plugin writes into its own llms.txt. */
const AM_LLMS_HOSTINGER_SIGNATURE = '[comment]: # (Generated by Hostinger Tools Plugin)';

/** Our own signature (last line), so we only ever overwrite our own file or Hostinger's. */
const AM_LLMS_SIGNATURE = '[comment]: # (Generated by the apnamerit theme from data/*.json)';

/**
 * "Program at Campus (Shift)" for a record.
 */
function am_record_name( array $r ): string {
	$campus = (string) ( $r['campus'] ?? '' );
	return (string) $r['program'] . ( '' !== $campus ? ' at ' . $campus : '' ) . ( ! empty( $r['shift'] ) ? ' (' . $r['shift'] . ')' : '' );
}

/**
 * Quotable, self-contained sentences for the default view of a university's merit data:
 * range, highest, lowest and the biggest moves against the previous year. Plain text.
 *
 * @return string[]
 */
function am_quotables( array $uni, string $list = '', string $cat = '' ): array {
	$list = '' !== $list ? $list : (string) ( $uni['defaults']['list'] ?? 'Final' );
	$cat  = '' !== $cat ? $cat : (string) ( $uni['defaults']['category'] ?? 'Open merit' );
	$rows = am_default_rows( $uni, $list, $cat );
	if ( ! $rows ) {
		return array();
	}
	$year  = am_uni_year( $uni, $list, $cat );
	$cur   = array_values( array_filter( $rows, fn( $r ) => (int) $r['year'] === $year ) );
	usort( $cur, fn( $a, $b ) => (float) $b['closing'] <=> (float) $a['closing'] );
	$short = (string) ( $uni['short'] ?? $uni['name'] ?? '' );
	$ctx   = 'the ' . $year . ' ' . $list . ' list (' . strtolower( $cat ) . ')';
	$out   = array();

	$top = $cur[0];
	$low = $cur[ count( $cur ) - 1 ];
	if ( count( $cur ) > 1 ) {
		$out[] = sprintf( 'In %s, %s closing aggregates ranged from %s to %s across %d programs and campuses.', $ctx, $short, am_pct( $top['closing'] ), am_pct( $low['closing'] ), count( $cur ) );
	}
	$out[] = sprintf( 'The highest %s closing aggregate in %s was %s, for %s.', $short, $ctx, am_pct( $top['closing'] ), am_record_name( $top ) );
	if ( count( $cur ) > 1 ) {
		$out[] = sprintf( 'The lowest %s closing aggregate in %s was %s, for %s.', $short, $ctx, am_pct( $low['closing'] ), am_record_name( $low ) );
	}

	// Biggest rise and drop against the previous year (same program, campus, shift, list, category).
	$prev = array();
	foreach ( $rows as $r ) {
		if ( (int) $r['year'] === $year - 1 ) {
			$prev[ $r['program'] . '|' . ( $r['campus'] ?? '' ) . '|' . ( $r['shift'] ?? '' ) ] = (float) $r['closing'];
		}
	}
	$moves = array();
	foreach ( $cur as $r ) {
		$k = $r['program'] . '|' . ( $r['campus'] ?? '' ) . '|' . ( $r['shift'] ?? '' );
		if ( isset( $prev[ $k ] ) ) {
			$moves[] = array( $r, (float) $r['closing'] - $prev[ $k ] );
		}
	}
	if ( $moves ) {
		usort( $moves, fn( $a, $b ) => $a[1] <=> $b[1] );
		$avg   = array_sum( array_column( $moves, 1 ) ) / count( $moves );
		$out[] = sprintf( 'On average, %s closing aggregates %s by %s points from %d to %d (%d programs listed in both years).', $short, $avg < 0 ? 'fell' : 'rose', number_format( abs( $avg ), 2 ), $year - 1, $year, count( $moves ) );
		$drop  = $moves[0];
		$rise  = $moves[ count( $moves ) - 1 ];
		if ( $drop[1] < 0 ) {
			$out[] = sprintf( '%s closed at %s in %d, %s points below %d.', am_record_name( $drop[0] ), am_pct( $drop[0]['closing'] ), $year, number_format( abs( $drop[1] ), 2 ), $year - 1 );
		}
		if ( $rise[1] > 0 ) {
			$out[] = sprintf( '%s closed at %s in %d, %s points above %d.', am_record_name( $rise[0] ), am_pct( $rise[0]['closing'] ), $year, number_format( $rise[1], 2 ), $year - 1 );
		}
	}
	return $out;
}

/**
 * "Key figures" list printed under a merit table.
 */
function am_facts_html( array $uni, string $list = '', string $cat = '' ): string {
	$facts = am_quotables( $uni, $list, $cat );
	if ( ! $facts ) {
		return '';
	}
	$out = '<div class="am-facts"><p><strong>Key figures</strong></p><ul>';
	foreach ( $facts as $f ) {
		$out .= '<li>' . esc_html( $f ) . '</li>';
	}
	return $out . '</ul></div>';
}

